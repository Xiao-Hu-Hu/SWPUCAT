package conversationapp

import (
	"context"
	"encoding/json"
	"errors"
	"strings"
	"time"
	"unicode/utf8"

	"SWPUCAT/internal/domain/conversation"
	"SWPUCAT/internal/domain/shared"

	"gorm.io/gorm"
)

const (
	defaultRecentMessageLimit    = 20
	defaultConversationListLimit = 100
	maxConversationListLimit     = 200
	maxConversationHistoryLimit  = 500
	defaultCleanupBatchSize      = 100
	maxCleanupBatchSize          = 1000
	maxRetentionDays             = 3650
)

type Service struct {
	repo conversation.Repository
}

func NewService(repo conversation.Repository) *Service {
	return &Service{repo: repo}
}

type ConversationDTO struct {
	ID              int64  `json:"id"`
	SessionID       string `json:"session_id"`
	Title           string `json:"title,omitempty"`
	RollingSummary  string `json:"rolling_summary,omitempty"`
	LastSourcesJSON string `json:"last_sources_json"`
	LastActiveAt    string `json:"last_active_at"`
	CreatedAt       string `json:"created_at"`
}

type MessageDTO struct {
	ID            int64  `json:"id"`
	Role          string `json:"role"`
	Content       string `json:"content"`
	ToolName      string `json:"tool_name,omitempty"`
	ToolResult    string `json:"tool_result,omitempty"`
	CitationsJSON string `json:"citations_json"`
	TokenCount    int    `json:"token_count"`
	CreatedAt     string `json:"created_at"`
}

type ContextDTO struct {
	Conversation ConversationDTO `json:"conversation"`
	Messages     []MessageDTO    `json:"messages"`
}

type RecordTurnRequest struct {
	UserContent         string
	AssistantContent    string
	AssistantToolName   string
	AssistantToolResult string
	CitationsJSON       string
	UserTokenCount      int
	AssistantTokenCount int
	// RollingSummary is generated by the Agent only when history needs
	// compaction. An empty value intentionally clears a stale summary.
	RollingSummary  *string
	LastSourcesJSON *string
}

type CleanupResult struct {
	Before        string `json:"before"`
	RetentionDays int    `json:"retention_days"`
	DryRun        bool   `json:"dry_run"`
	Eligible      int64  `json:"eligible"`
	Deleted       int64  `json:"deleted"`
}

// GetOrCreate makes the session handle durable. Because lookup is already
// filtered by userID, another account using the same opaque session string
// receives a distinct, empty conversation rather than another user's context.
func (s *Service) GetOrCreate(ctx context.Context, userID int64, sessionID, title string) (*ConversationDTO, error) {
	if s == nil || s.repo == nil {
		return nil, shared.ErrInternal
	}
	if userID <= 0 || strings.TrimSpace(sessionID) == "" {
		return nil, shared.ErrValidation
	}
	item, err := s.repo.FindBySession(ctx, userID, strings.TrimSpace(sessionID))
	if err == nil {
		return toConversationDTO(item), nil
	}
	if !isNotFound(err) {
		return nil, err
	}
	if strings.TrimSpace(title) == "" {
		title = conversation.DefaultTitle
	}
	item, err = conversation.New(userID, sessionID, title)
	if err != nil {
		return nil, shared.ErrValidation
	}
	if err := s.repo.Create(ctx, item); err != nil {
		if errors.Is(err, conversation.ErrDeletedConversation) {
			return nil, conversation.ErrDeletedConversation
		}
		// A browser can submit two first messages concurrently. If another
		// request won the unique (user_id, session_id) insert race, return the
		// durable row it created instead of failing a valid chat request.
		if existing, findErr := s.repo.FindBySession(ctx, userID, item.SessionID); findErr == nil {
			return toConversationDTO(existing), nil
		}
		return nil, err
	}
	return toConversationDTO(item), nil
}

// Delete permanently removes one owned conversation. The repository keeps a
// one-way session hash tombstone so the same handle cannot silently create a
// new conversation after the user has explicitly deleted it. Missing rows are
// treated as success, making retries idempotent without revealing whether a
// session belongs to another account.
func (s *Service) Delete(ctx context.Context, userID int64, sessionID string) error {
	if s == nil || s.repo == nil || userID <= 0 || strings.TrimSpace(sessionID) == "" {
		return shared.ErrValidation
	}
	lifecycle, ok := s.repo.(conversation.LifecycleRepository)
	if !ok {
		return shared.ErrInternal
	}
	return lifecycle.DeleteOwned(ctx, userID, strings.TrimSpace(sessionID), time.Now())
}

// CleanupExpired previews or executes retention cleanup. Destructive cleanup
// is impossible unless execute is explicitly true; retention=0 is handled by
// configuration as disabled and is rejected here to avoid accidental defaults.
func (s *Service) CleanupExpired(ctx context.Context, now time.Time, retentionDays, batchSize int, execute bool) (*CleanupResult, error) {
	if s == nil || s.repo == nil || now.IsZero() || retentionDays < 1 || retentionDays > maxRetentionDays {
		return nil, shared.ErrValidation
	}
	if batchSize <= 0 {
		batchSize = defaultCleanupBatchSize
	}
	if batchSize > maxCleanupBatchSize {
		return nil, shared.ErrValidation
	}
	lifecycle, ok := s.repo.(conversation.LifecycleRepository)
	if !ok {
		return nil, shared.ErrInternal
	}
	before := now.AddDate(0, 0, -retentionDays)
	eligible, err := lifecycle.CountExpired(ctx, before)
	if err != nil {
		return nil, err
	}
	result := &CleanupResult{
		Before: before.Format(time.RFC3339), RetentionDays: retentionDays,
		DryRun: !execute, Eligible: eligible,
	}
	if !execute || eligible == 0 {
		return result, nil
	}
	for {
		deleted, deleteErr := lifecycle.DeleteExpired(ctx, before, batchSize, now)
		if deleteErr != nil {
			return nil, deleteErr
		}
		result.Deleted += deleted
		if deleted == 0 || deleted < int64(batchSize) {
			break
		}
	}
	return result, nil
}

// ListRecent returns only conversations owned by userID, ordered by the most
// recently active turn. Empty conversations are included so a newly created
// chat can remain visible before its first message is sent.
func (s *Service) ListRecent(ctx context.Context, userID int64, limit int) ([]ConversationDTO, error) {
	if s == nil || s.repo == nil || userID <= 0 {
		return nil, shared.ErrValidation
	}
	if limit <= 0 {
		limit = defaultConversationListLimit
	}
	if limit > maxConversationListLimit {
		return nil, shared.ErrValidation
	}
	items, err := s.repo.ListRecent(ctx, userID, limit)
	if err != nil {
		return nil, err
	}
	result := make([]ConversationDTO, 0, len(items))
	for _, item := range items {
		if item == nil {
			continue
		}
		result = append(result, *toConversationDTO(item))
	}
	return result, nil
}

// UpdateTitle changes only the title owned by the authenticated user. A
// rename is deliberately not an activity update, so it does not reorder the
// conversation list.
func (s *Service) UpdateTitle(ctx context.Context, userID int64, sessionID, title string) (*ConversationDTO, error) {
	if s == nil || s.repo == nil || userID <= 0 || strings.TrimSpace(sessionID) == "" {
		return nil, shared.ErrValidation
	}
	title = strings.TrimSpace(title)
	if title == "" || utf8.RuneCountInString(title) > conversation.MaxTitleRunes {
		return nil, shared.ErrValidation
	}
	item, err := s.repo.FindBySession(ctx, userID, strings.TrimSpace(sessionID))
	if err != nil {
		if isNotFound(err) {
			return nil, shared.ErrNotFound
		}
		return nil, err
	}
	if err := s.repo.UpdateTitle(ctx, userID, item.SessionID, title); err != nil {
		if isNotFound(err) {
			return nil, shared.ErrNotFound
		}
		return nil, err
	}
	item.Title = title
	item.TitleCustomized = true
	item.UpdatedAt = time.Now()
	return toConversationDTO(item), nil
}

func (s *Service) LoadContext(ctx context.Context, userID int64, sessionID string, limit int) (*ContextDTO, error) {
	if s == nil || s.repo == nil || userID <= 0 || strings.TrimSpace(sessionID) == "" {
		return nil, shared.ErrValidation
	}
	if limit <= 0 {
		limit = defaultRecentMessageLimit
	}
	if limit > maxConversationHistoryLimit {
		return nil, shared.ErrValidation
	}
	item, err := s.repo.FindBySession(ctx, userID, strings.TrimSpace(sessionID))
	if err != nil {
		if isNotFound(err) {
			return nil, shared.ErrNotFound
		}
		return nil, err
	}
	messages, err := s.repo.ListRecentMessages(ctx, userID, item.SessionID, limit)
	if err != nil {
		return nil, err
	}
	result := &ContextDTO{Conversation: *toConversationDTO(item), Messages: make([]MessageDTO, 0, len(messages))}
	for _, message := range messages {
		result.Messages = append(result.Messages, *toMessageDTO(message))
	}
	return result, nil
}

// RecordTurn writes the two user-visible sides of one Agent turn and then
// updates the optional rolling summary and source memory. The caller supplies
// JSON source/citation payloads so the Agent package remains independent of a
// particular retrieval implementation.
func (s *Service) RecordTurn(ctx context.Context, userID int64, sessionID string, req RecordTurnRequest) (*ConversationDTO, error) {
	if s == nil || s.repo == nil || userID <= 0 || strings.TrimSpace(sessionID) == "" {
		return nil, shared.ErrValidation
	}
	item, err := s.repo.FindBySession(ctx, userID, strings.TrimSpace(sessionID))
	if err != nil {
		if isNotFound(err) {
			return nil, shared.ErrNotFound
		}
		return nil, err
	}
	citations, err := normalizeJSONArray(req.CitationsJSON)
	if err != nil {
		return nil, shared.ErrValidation
	}
	userMessage, err := conversation.NewMessage(item.ID, conversation.RoleUser, req.UserContent, "", "", "[]", req.UserTokenCount)
	if err != nil {
		return nil, shared.ErrValidation
	}
	assistantMessage, err := conversation.NewMessage(item.ID, conversation.RoleAssistant, req.AssistantContent, req.AssistantToolName, req.AssistantToolResult, citations, req.AssistantTokenCount)
	if err != nil {
		return nil, shared.ErrValidation
	}
	summary := item.RollingSummary
	sources := item.LastSourcesJSON
	if req.RollingSummary != nil {
		summary = strings.TrimSpace(*req.RollingSummary)
	}
	if req.LastSourcesJSON != nil {
		sources, err = normalizeJSONArray(*req.LastSourcesJSON)
		if err != nil {
			return nil, shared.ErrValidation
		}
	}
	if !item.TitleCustomized {
		item.Title = titleFromFirstMessage(req.UserContent)
		item.TitleCustomized = true
	}
	activeAt := time.Now()
	if err := item.UpdateContext(summary, sources, activeAt); err != nil {
		return nil, shared.ErrValidation
	}
	if err := s.repo.RecordTurn(ctx, userID, item.SessionID, item.Title, item.TitleCustomized, userMessage, assistantMessage, item.RollingSummary, item.LastSourcesJSON, item.LastActiveAt); err != nil {
		return nil, err
	}
	return toConversationDTO(item), nil
}

func titleFromFirstMessage(value string) string {
	parts := strings.Fields(strings.TrimSpace(value))
	if len(parts) == 0 {
		return conversation.DefaultTitle
	}
	title := strings.Join(parts, " ")
	runes := []rune(title)
	const maxAutoTitleRunes = 48
	if len(runes) > maxAutoTitleRunes {
		title = string(runes[:maxAutoTitleRunes]) + "…"
	}
	return title
}

func normalizeJSONArray(value string) (string, error) {
	value = strings.TrimSpace(value)
	if value == "" {
		return "[]", nil
	}
	if utf8.RuneCountInString(value) > 64000 || !json.Valid([]byte(value)) {
		return "", errors.New("invalid JSON")
	}
	var array []json.RawMessage
	if err := json.Unmarshal([]byte(value), &array); err != nil {
		return "", err
	}
	return value, nil
}

func isNotFound(err error) bool {
	return errors.Is(err, shared.ErrNotFound) || errors.Is(err, gorm.ErrRecordNotFound)
}

func toConversationDTO(item *conversation.Conversation) *ConversationDTO {
	return &ConversationDTO{ID: item.ID, SessionID: item.SessionID, Title: item.Title, RollingSummary: item.RollingSummary, LastSourcesJSON: item.LastSourcesJSON, LastActiveAt: item.LastActiveAt.Format(time.RFC3339), CreatedAt: item.CreatedAt.Format(time.RFC3339)}
}

func toMessageDTO(message *conversation.Message) *MessageDTO {
	return &MessageDTO{ID: message.ID, Role: string(message.Role), Content: message.Content, ToolName: message.ToolName, ToolResult: message.ToolResult, CitationsJSON: message.CitationsJSON, TokenCount: message.TokenCount, CreatedAt: message.CreatedAt.Format(time.RFC3339)}
}
